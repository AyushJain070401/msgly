/**
 * Bakes the brand marks we use into app/icons.ts so the 3000-icon simple-icons
 * package stays a devDependency and never reaches the bundle.
 *
 * simple-icons dropped a number of corporate marks over trademark policy
 * (Slack, AWS, Twilio, Microsoft, SendGrid and the SMS vendors); those are
 * drawn by hand in app/components/CustomMarks.tsx instead.
 *
 *   node scripts/gen-icons.mjs
 */
import { writeFileSync } from 'node:fs';
import * as si from 'simple-icons';

// package -> simple-icons slug
const FROM_SIMPLE_ICONS = {
  '@msgly/telegram': 'telegram',
  '@msgly/whatsapp': 'whatsapp',
  '@msgly/messenger': 'messenger',
  '@msgly/instagram': 'instagram',
  '@msgly/line': 'line',
  '@msgly/discord': 'discord',
  '@msgly/wechat': 'wechat',
  '@msgly/viber': 'viber',
  '@msgly/mattermost': 'mattermost',
  '@msgly/rocketchat': 'rocketdotchat',
  '@msgly/googlechat': 'googlechat',
  '@msgly/gmail': 'gmail',
  '@msgly/resend': 'resend',
  '@msgly/vonage-sms': 'vonage',
  '@msgly/fcm': 'firebase',
  '@msgly/reddit': 'reddit',
};

const slugToExport = (s) => 'si' + s[0].toUpperCase() + s.slice(1);

const entries = [];

for (const [pkg, slug] of Object.entries(FROM_SIMPLE_ICONS)) {
  const icon = si[slugToExport(slug)];
  if (!icon) throw new Error(`simple-icons no longer ships "${slug}" (for ${pkg})`);
  entries.push(`  '${pkg}': { kind: 'path', hex: '#${icon.hex}', d: '${icon.path}' },`);
}

const out = `// GENERATED by scripts/gen-icons.mjs — do not edit by hand.
// Brand paths come from simple-icons (icons are CC0; the marks remain the
// property of their owners). Brands simple-icons no longer ships are drawn by
// hand in app/components/CustomMarks.tsx.

export type Mark = { kind: 'path'; hex: string; d: string };

export const marks: Record<string, Mark> = {
${entries.join('\n')}
};
`;

writeFileSync(new URL('../app/icons.ts', import.meta.url), out);
console.log(`wrote app/icons.ts — ${entries.length} marks`);
